function season(peaks: number[], notes: Partial<Record<number, string>>) {
  return MONTHS.map((month, i) => {
    const near = peaks.some((p) => Math.min(Math.abs(p - i), 12 - Math.abs(p - i)) === 1);
    return {
      month,
      score: peaks.includes(i) ? 3 : near ? 2 : 1,
      note: notes[i] || (peaks.includes(i) ? "Excellent wildlife viewing" : "A quieter, greener season"),
    };
  });
}

function days(
  rows: [string, string, string, string, string, string][],
  images: string[],
): TourDay[] {
  return rows.map((r, i) => ({
    day: i + 1,
    title: r[0],
    location: r[1],
    stay: r[2],
    meals: r[3],
    activities: r[4],
    description: r[5],
    image: images[i % images.length],
  }));
}

